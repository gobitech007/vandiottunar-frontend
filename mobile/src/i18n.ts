export const strings = { en, ta }
export type Lang = keyof typeof strings

export const LangContext = createContext<{ lang: Lang; t: Strings; setLang: (l: Lang) => void }>({
  lang: 'ta',
  t: ta,
  setLang: () => {},
})

export const useT = () => useContext(LangContext)

export function errorText(err: unknown, t: Strings): string {
  const e = err as { status?: number; message?: string }
  if (e?.status === 0) return t.networkError
  return e?.message ?? t.networkError
}
