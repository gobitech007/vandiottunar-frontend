export const strings = { en, ta }
export type Lang = keyof typeof strings

const LANG_KEY = 'vo_lang'

function initialLang(): Lang {
  try {
    return localStorage.getItem(LANG_KEY) === 'en' ? 'en' : 'ta'
  } catch {
    return 'ta'
  }
}

const LangContext = createContext<{ lang: Lang; t: Strings; setLang: (l: Lang) => void }>({
  lang: 'ta',
  t: ta,
  setLang: () => {},
})

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang)
  const value = useMemo(
    () => ({
      lang,
      t: strings[lang],
      setLang: (l: Lang) => {
        setLangState(l)
        try {
          localStorage.setItem(LANG_KEY, l)
        } catch {
          /* ignore */
        }
      },
    }),
    [lang],
  )
  return <LangContext.Provider value={value}>{children}</LangContext.Provider>
}

export const useT = () => useContext(LangContext)

const ENGLISH_ONLY = { lang: 'en' as Lang, t: en, setLang: () => {} }

/** The admin panel is English only; shared components inside it use English too. */
export function EnglishOnly({ children }: { children: ReactNode }) {
  return <LangContext.Provider value={ENGLISH_ONLY}>{children}</LangContext.Provider>
}
